#!/usr/bin/env node
// Bakes crates/max-assets/src/save/unit_names.rs from the re-MAX object-type
// ini files: the TAGNAME -> in-game display name table, plus the set of unit
// types players can build and control (the Edit Save Data Upgrades roster).
//
// Source of truth: the sister re-MAX project's rules inis (one section per
// ResourceID tag; `Buildable` defaults to yes, `Passive` to no). Only tags in
// the editor's canonical `UNIT_TYPE_NAMES` (save/unit_types.rs) are emitted,
// so non-save entries (TEST_HUB, projectile recipes) drop out naturally.
//
// A unit is player-buildable-and-controllable unless its ini section says
// `Buildable=no` (the alien units, the scenario-only RECCENTR/SHIELDGN) or
// `Passive=yes` (road/bridge/platform/block dressing) - both keys default to
// the buildable side, so an omitted key never drops a real unit (ARTILLRY's
// section carries no Factory yet, for one). Two hand-kept exceptions mirror
// the engine: MASTER is out (the Master Builder exists in the data but no
// factory builds it - max-port's builder tables never name it), and LANDMINE/
// SEAMINE are in despite `Buildable=no` (the engine's own upgrade menu lists
// a mine whenever its deployer is buildable,
// AbstractUpgradeMenu::IsUnitFiltered, and their attack and hits are real,
// editable stats).
//
// Usage: node tools/gen-unit-names.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const INI_DIR = '/media/ssd-projects/re-MAX/re-max/apps/game/assets/config/rules/object_types';
const CLASS_FILES = [
	'aircraft_types.ini',
	'building_types.ini',
	'infantry_types.ini',
	'naval_types.ini',
	'vehicle_types.ini',
];
const MINE_EXCEPTIONS = ['LANDMINE', 'SEAMINE'];
const NO_BUILDER = ['MASTER'];
const OUT = path.join(ROOT, 'crates/max-assets/src/save/unit_names.rs');
const UNIT_TYPES_RS = path.join(ROOT, 'crates/max-assets/src/save/unit_types.rs');

// The canonical ResourceID tag order, parsed off UNIT_TYPE_NAMES so the two
// tables can never disagree about what a save unit type is.
const canonical = [];
{
	const src = fs.readFileSync(UNIT_TYPES_RS, 'utf8');
	const body = src.match(/UNIT_TYPE_NAMES[^=]*= \[([^\]]*)\]/);
	if (!body) throw new Error('UNIT_TYPE_NAMES not found in unit_types.rs');
	for (const m of body[1].matchAll(/"([A-Z0-9_]+)"/g)) canonical.push(m[1]);
	if (canonical.length !== 0x5d) throw new Error(`expected 0x5D tags, got ${canonical.length}`);
}

// Parse every class ini: one section per tag, `Key=Value` lines, `;` comments.
const sections = new Map();
for (const file of CLASS_FILES) {
	const text = fs.readFileSync(path.join(INI_DIR, file), 'utf8');
	let section = null;
	for (const raw of text.split(/\r?\n/)) {
		const line = raw.trim();
		if (!line || line.startsWith(';')) continue;
		const head = line.match(/^\[(.+)\]$/);
		if (head) {
			// The leading [<Class>Types] index section is not a unit.
			section = head[1].endsWith('Types') ? null : head[1];
			if (section && !sections.has(section)) sections.set(section, {});
			continue;
		}
		const kv = line.match(/^([A-Za-z0-9_]+)=(.*)$/);
		if (kv && section) sections.get(section)[kv[1]] = kv[2].trim();
	}
}

const names = [];
const player = [];
for (const tag of canonical) {
	const s = sections.get(tag);
	if (!s) continue;
	if (s.Name) {
		if (!/^[\x20-\x7e]*$/.test(s.Name)) throw new Error(`non-ASCII name for ${tag}: ${s.Name}`);
		names.push([tag, s.Name]);
	}
	const buildable =
		(s.Buildable ?? 'yes') !== 'no' && (s.Passive ?? 'no') !== 'yes' && !NO_BUILDER.includes(tag);
	if (buildable || MINE_EXCEPTIONS.includes(tag)) player.push(tag);
}
if (names.length < 40 || player.length < 40) {
	throw new Error(`suspiciously small tables (${names.length} names, ${player.length} player tags)`);
}

const nameRows = names.map(([t, n]) => `\t("${t}", "${n}"),`).join('\n');
const playerRows = player.map((t) => `\t"${t}",`).join('\n');
const out = `//! GENERATED by \`node tools/gen-unit-names.mjs\` - do not hand-edit.
//!
//! In-game unit display names and the player-unit roster, baked from the
//! re-MAX rules inis (\`assets/config/rules/object_types\`). The tags are the
//! same \`ResourceID\` names as [\`UNIT_TYPE_NAMES\`](super::UNIT_TYPE_NAMES);
//! both tables ride in canonical id order.

/// \`ResourceID\` tag -> the unit's proper in-game name (\`Name=\` in the rules
/// inis). Tags without a section or with an empty name (decoration, FX, the
/// unnamed SUPRTPLT) are absent - display falls back to the tag.
pub const UNIT_DISPLAY_NAMES: [(&str, &str); ${names.length}] = [
${nameRows}
];

/// Tags of every unit players can build and control - the set the game's own
/// upgrade menus offer: neither \`Buildable=no\` (alien units, scenario-only
/// buildings) nor \`Passive=yes\` (road/bridge/platform/block dressing), minus
/// the factory-less MASTER. LANDMINE and SEAMINE ride along because the
/// engine lists a mine whenever its deployer is buildable
/// (\`AbstractUpgradeMenu::IsUnitFiltered\`).
pub const PLAYER_UNIT_TAGS: [&str; ${player.length}] = [
${playerRows}
];

/// The proper in-game name for a \`ResourceID\` tag, \`None\` where the rules
/// carry no (non-empty) name - callers show the tag itself then.
pub fn unit_display_name(tag: &str) -> Option<&'static str> {
	UNIT_DISPLAY_NAMES.iter().find(|(t, _)| *t == tag).map(|(_, n)| *n)
}

/// Whether a save \`unit_type\` is a unit players can build and control (see
/// [\`PLAYER_UNIT_TAGS\`]) - the Upgrades roster and its validation gate.
pub fn is_player_unit_type(unit_type: u16) -> bool {
	super::unit_type_name(unit_type).is_some_and(|tag| PLAYER_UNIT_TAGS.contains(&tag))
}
`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${names.length} names, ${player.length} player tags`);
