    /// ASCII art round-trips: '#' inks a cell, the grid is the art's own side,
    /// and out-of-range reads answer clear rather than panicking.
    #[test]
    fn art_inks_cells_and_reports_its_grid() {
        let s = Stencil::art([
            "#...............",
            ".##.............",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "...............#",
        ]);
        assert_eq!(s.grid(), 16);
        assert!(s.cell(0, 0), "row 0 col 0 is inked");
        assert!(s.cell(1, 1) && s.cell(2, 1), "row 1 inks cols 1-2");
        assert!(!s.cell(3, 1), "and stops there");
        assert!(s.cell(15, 15), "the far corner reaches bit 15");
        assert!(!s.cell(16, 0) && !s.cell(0, 16), "out of range reads clear");
        assert!(Stencil::EMPTY.is_empty() && !s.is_empty());
    }

    /// A 24-cell stencil addresses all 24 columns — the rows are wide enough
    /// (a 16-bit row would silently drop cell 16 and up).
    #[test]
    fn a_wide_grid_addresses_every_column() {
        let s = PENCIL.pick(24).0;
        assert_eq!(s.grid(), 24);
        let mut dl = DrawList::new();
        s.draw(&mut dl, Rect::new(0.0, 0.0, 24.0, 24.0), Rgba::WHITE);
        let right = dl
            .cmds
            .iter()
            .filter_map(|c| match c {
                DrawCmd::Solid { rect, .. } => Some(rect.right()),
                _ => None,
            })
            .fold(0.0f32, f32::max);
        assert!(right > 16.0, "art past cell 16 survives, got {right}");
    }

    /// `draw` merges each row's inked cells into one quad per run, scaled to
    /// the target rect.
    #[test]
    fn draw_merges_runs_into_scaled_quads() {
        let s = Stencil::art([
            "##..##..........",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
            "................",
        ]);
        let mut dl = DrawList::new();
        // A 32x32 box: each cell is 2x2.
        s.draw(&mut dl, Rect::new(10.0, 20.0, 32.0, 32.0), Rgba::WHITE);
        let quads: Vec<Rect> = dl
            .cmds
            .iter()
            .filter_map(|c| match c {
                DrawCmd::Solid { rect, .. } => Some(*rect),
                _ => None,
            })
            .collect();
        assert_eq!(quads.len(), 2, "two runs, two quads");
        assert_eq!(quads[0], Rect::new(10.0, 20.0, 4.0, 2.0), "cols 0-1 merge");
        assert_eq!(quads[1], Rect::new(18.0, 20.0, 4.0, 2.0), "cols 4-5 merge");
    }

    /// A 24px key picks the art drawn for the scale in force, in a box where one
    /// cell is one physical pixel: 16 cells at 100%, 20 at 125%, 24 at 150%.
    #[test]
    fn fit_picks_the_art_for_the_scale_and_stamps_it_1to1() {
        let key = Rect::new(10.0, 20.0, 24.0, 24.0);
        for (scale, grid) in [(1.0, 16), (1.25, 20), (1.5, 24)] {
            let (stencil, rect) = fit(PENCIL, key, scale);
            assert_eq!(stencil.grid(), grid, "{scale}x picks the {grid}-cell art");
            let cell = (rect.w * scale) / grid as f32;
            assert!(
                (cell - 1.0).abs() < 1e-3,
                "{scale}x: a cell is {cell} physical px, want 1"
            );
            assert!(
                (rect.x * scale).fract().abs() < 1e-3 && (rect.y * scale).fract().abs() < 1e-3,
                "{scale}x: the stencil's corner sits on a whole physical pixel"
            );
            assert!(rect.w <= key.w && rect.h <= key.h, "{scale}x: fits its key");
        }
    }

    /// Art too big for the ask is passed over, and a size with no art of its own
    /// falls back to whole-pixel replication of a smaller grid rather than
    /// resampling it. Nothing fits at all -> the smallest, for the clip to crop.
    #[test]
    fn pick_never_resamples() {
        assert_eq!(PENCIL.pick(16), (PENCIL.pick(16).0, 16), "exact art at 16");
        assert_eq!(PENCIL.pick(22).0.grid(), 20, "22px takes the 20-cell art");
        assert_eq!(
            PENCIL.pick(32),
            (PENCIL.pick(16).0, 32),
            "32px is 16 doubled"
        );
        assert_eq!(
            PENCIL.pick(48),
            (PENCIL.pick(24).0, 48),
            "48px is 24 doubled"
        );
        assert_eq!(
            PENCIL.pick(8),
            (PENCIL.pick(16).0, 16),
            "nothing fits: smallest"
        );
    }

