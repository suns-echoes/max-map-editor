//! Stencil icons: a one-bit pictogram vocabulary, authored per UI size.
//!
//! An [`Icon`] is pixel art, not a path — and pixel art is only crisp at the
//! size it was drawn for. So an icon is not one stencil that gets scaled: it is
//! a set of [`Stencil`]s, one per UI size, each authored as ASCII art (`#` =
//! inked) and checked at **compile time** by the `const` constructor. The
//! standard set carries a 16-cell grid for 100%, a 20-cell one for 125% and a
//! 24-cell one for 150%. [`fit`] picks the art for the scale in force and sizes
//! its box so that **one cell is one physical pixel** — the stencil is stamped
//! 1:1, never resampled onto a fractional grid where some cells would come out
//! a pixel wide and their neighbours two.
//!
//! Drawing decomposes each row into merged horizontal runs of
//! [`DrawList::fill_rect`] — the same axis-aligned-quads-only vocabulary as the
//! rest of the toolkit (`DrawList` has no path primitive, and a stencil belongs
//! with the bevels and 1px rules around it, where a smooth vector would be the
//! one anti-aliased stranger on a machined panel).
//!
//! Widgets do not draw a stencil directly: they hand it to
//! [`Theme::icon`](crate::theme::Theme::icon) with a state-appropriate ink, the
//! way text goes through `Theme::text_colored` — so a theme can emboss, recolor
//! or re-treat every icon in one place. [`Button::icon`](crate::Button::icon)
//! is the standard consumer, and calls [`fit`] for it.
//!
//! The set below is the toolkit's standard vocabulary — generic pictograms
//! (a pencil, a bucket, a marquee), not app commands. A host needing a glyph
//! this module lacks adds it **here**, so every consumer shares it; the ASCII
//! form is deliberately cheap to author and review.
//!
//! Authoring rules of thumb: keep a ~1-cell margin, prefer a stroke that grows
//! with the grid (1 cell at 16, 1-2 at 20, 2 at 24), and design the
//! *silhouette* first — one-bit art has no shading. Draw each size, don't
//! trace a scaled copy: the whole point is that 20 and 24 get the detail their
//! extra pixels can carry.

use crate::color::Rgba;
use crate::draw::DrawList;
use crate::geom::Rect;

/// Cells per side of the base stencil — the grid an icon is drawn on at 100%.
pub const GRID: usize = 16;

/// The widest grid a [`Stencil`] can hold (room for a 200% set).
const MAX_GRID: usize = 32;

/// A square one-bit stencil at ONE grid size: `grid` rows of `grid` cells, row
/// `r` bit `c` being cell `(c, r)` from the top-left. `Copy`, comparable, and
/// `const`-constructible from ASCII art via [`Stencil::art`].
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Stencil {
    grid: u8,
    rows: [u32; MAX_GRID],
}

impl Stencil {
    /// A slot with no art in it — [`Icon::pick`] passes over it, so a size an
    /// icon has not been drawn for falls back to one it has.
    pub const EMPTY: Self = Self {
        grid: 0,
        rows: [0; MAX_GRID],
    };

    /// Builds a stencil from square ASCII art: `#` inks a cell, anything else
    /// leaves it clear. The art must be square — `N` rows of exactly `N` bytes
    /// — which is checked at compile time for a `const`, so malformed art
    /// cannot reach a draw.
    pub const fn art<const N: usize>(rows: [&str; N]) -> Self {
        assert!(N > 0 && N <= MAX_GRID, "a stencil grid is 1..=32 cells");
        let mut out = [0u32; MAX_GRID];
        let mut r = 0;
        while r < N {
            let bytes = rows[r].as_bytes();
            assert!(bytes.len() == N, "a stencil's art is square");
            let mut c = 0;
            while c < N {
                if bytes[c] == b'#' {
                    out[r] |= 1 << c;
                }
                c += 1;
            }
            r += 1;
        }
        Self {
            grid: N as u8,
            rows: out,
        }
    }

    /// Cells per side.
    pub fn grid(&self) -> usize {
        self.grid as usize
    }

    /// True for [`Stencil::EMPTY`] — a size this icon was never drawn for.
    pub fn is_empty(&self) -> bool {
        self.grid == 0
    }

    /// Whether cell `(c, r)` is inked. Out-of-range reads answer `false`.
    pub fn cell(&self, c: usize, r: usize) -> bool {
        let g = self.grid as usize;
        c < g && r < g && self.rows[r] & (1 << c) != 0
    }

    /// Stamps the stencil into `rect` in `ink`, one merged quad per horizontal
    /// run (a cell is `rect.w / grid` × `rect.h / grid`). Callers wanting the
    /// themed treatment go through [`Theme::icon`](crate::theme::Theme::icon)
    /// instead; this is the raw stamp it builds on. Hand it a rect [`fit`]
    /// sized, so a cell lands on whole physical pixels.
    pub fn draw(&self, dl: &mut DrawList, rect: Rect, ink: Rgba) {
        let g = self.grid as usize;
        if g == 0 {
            return;
        }
        let (sx, sy) = (rect.w / g as f32, rect.h / g as f32);
        for (r, bits) in self.rows[..g].iter().enumerate() {
            let mut c = 0;
            while c < g {
                if bits & (1 << c) == 0 {
                    c += 1;
                    continue;
                }
                let start = c;
                while c < g && bits & (1 << c) != 0 {
                    c += 1;
                }
                dl.fill_rect(
                    Rect::new(
                        rect.x + start as f32 * sx,
                        rect.y + r as f32 * sy,
                        (c - start) as f32 * sx,
                        sy,
                    ),
                    ink,
                );
            }
        }
    }
}

/// One pictogram, drawn once per UI size: the same mark on a 16-, 20- and
/// 24-cell grid, so every scale has art meant for its pixel count instead of a
/// resampled copy of a smaller one. Slots may be [`Stencil::EMPTY`].
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Icon {
    /// Ascending by grid — [`pick`](Self::pick) relies on the order.
    sizes: &'static [Stencil],
}

impl Icon {
    /// Collects an icon's art. Sizes must ascend by grid (checked at compile
    /// time for a `const`), and a `&[...]` literal of `const` stencils promotes
    /// to `'static`, so the standard set stays a plain `pub const`.
    pub const fn new(sizes: &'static [Stencil]) -> Self {
        assert!(!sizes.is_empty(), "an icon has at least one stencil");
        let mut i = 1;
        while i < sizes.len() {
            assert!(
                sizes[i - 1].grid < sizes[i].grid,
                "an icon's stencils ascend by grid"
            );
            i += 1;
        }
        Self { sizes }
    }

    /// The art to stamp at `want` physical pixels, and the side it covers:
    /// the largest whole number of cells that fits, preferring art drawn for
    /// that exact size.
    ///
    /// A cell is always a whole pixel. Where the wanted size is a multiple of a
    /// smaller grid but no art exists at the bigger one (a 32px key with only a
    /// 16-cell stencil), each cell simply becomes `k` pixels — replication, not
    /// resampling, so the mark stays exact. Art too big for `want` is passed
    /// over; if none fits at all, the smallest is stamped anyway and the caller's
    /// clip crops it.
    pub fn pick(&self, want: u32) -> (Stencil, u32) {
        let mut best: Option<(Stencil, u32)> = None;
        for &st in self.sizes {
            let grid = st.grid as u32;
            if grid == 0 {
                continue;
            }
            let k = want / grid;
            if k == 0 {
                continue;
            }
            let side = grid * k;
            // Ascending grids and `>=` together prefer the finer art on a tie.
            if best.is_none_or(|(_, prev)| side >= prev) {
                best = Some((st, side));
            }
        }
        best.unwrap_or_else(|| {
            let st = self.sizes[0];
            (st, st.grid as u32)
        })
    }
}

/// The art and box to stamp inside `key` at UI `scale`: the stencil drawn for
/// this size, in a box where **one cell is one physical pixel**, centred and
/// aligned to the physical pixel grid.
///
/// `key` asks for the largest whole multiple of [`GRID`] that fits it with a
/// little breathing room (a 24px key asks for 16 logical px, a 40px key for
/// 32); the ask is then taken to physical pixels, which is what the art is
/// chosen against. So a 24px key stamps the 16-cell art at 100%, the 20-cell
/// at 125% and the 24-cell at 150% — each 1:1, each growing with the chrome
/// around it.
pub fn fit(icon: Icon, key: Rect, scale: f32) -> (Stencil, Rect) {
    let s = scale.max(1e-4);
    let room = (key.w.min(key.h) - 4.0).max(GRID as f32);
    let nominal = (room / GRID as f32).floor().max(1.0) * GRID as f32;
    let (stencil, side) = icon.pick((nominal * s).round().max(1.0) as u32);
    let side = side as f32;
    let c = key.center();
    let (x, y) = (
        (c.x * s - side * 0.5).round(),
        (c.y * s - side * 0.5).round(),
    );
    (stencil, Rect::new(x / s, y / s, side / s, side / s))
} // --- the standard stencils ---------------------------------------------------
